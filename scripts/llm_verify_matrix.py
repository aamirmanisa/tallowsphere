#!/usr/bin/env python3
"""Verify every configured LLM provider and write a dated capability table.

R8 in docs/plans/2026-10-23-unified-integration-fix-plan.md: providers were
verified against a protocol mock, never against a real endpoint, because CI has
no keys. This script is the operator-run half of that: it reads the same
`llm.toml` the engine reads, asks each provider what it has with
`tallow llm verify <id>`, and writes what came back.

Rules this script keeps:

  * it never prints, stores or logs a key — only the provider id, protocol,
    model count, latency and status;
  * it refuses to run at all if a configured `key_file` is readable by group or
    other (mode & 0o077), because a "verification" that reads a leaked key is
    worse than no verification;
  * a provider that fails is recorded as failed with the engine's own message,
    not omitted — the table's value is that it shows what does not work.

Usage:
    scripts/llm_verify_matrix.py                    # writes docs/operations/llm-verify-<date>.md
    scripts/llm_verify_matrix.py --tallow target/debug/tallow --stdout
"""
from __future__ import annotations

import argparse
import datetime as dt
import os
import re
import stat
import subprocess
import sys
import tomllib
from pathlib import Path

CONFIG = Path(os.path.expanduser("~/.config/tallow/llm.toml"))
OUT_DIR = Path("docs/operations")


def fail(msg: str) -> int:
    print(f"llm_verify_matrix: {msg}", file=sys.stderr)
    return 1


def load_providers(config: Path) -> dict[str, dict]:
    if not config.exists():
        raise SystemExit(f"no provider config at {config}")
    data = tomllib.loads(config.read_text())
    return data.get("providers", {})


def check_key_permissions(providers: dict[str, dict]) -> None:
    """Refuse if any key file is group/other readable. The engine's own rule."""
    for pid, cfg in providers.items():
        kf = cfg.get("key_file")
        if not kf:
            continue
        p = Path(os.path.expanduser(kf))
        if not p.exists():
            raise SystemExit(f"llm_verify_matrix: {pid}: key_file {p} does not exist")
        mode = stat.S_IMODE(p.stat().st_mode)
        if mode & 0o077:
            raise SystemExit(
                f"llm_verify_matrix: {pid}: key_file {p} is mode {mode:o}; "
                "it must be 0600 before any verification runs"
            )


VERIFY_RE = re.compile(r"^\s*(ok|error)\s*:\s*(?P<body>.*)$", re.IGNORECASE)
MODELS_RE = re.compile(r"(?P<count>\d+)\s+models?", re.IGNORECASE)
MS_RE = re.compile(r"in\s+(?P<ms>\d+)\s*ms", re.IGNORECASE)


def verify_one(tallow: str, pid: str) -> tuple[str, int, str, str]:
    """Return (status, models, latency, detail) with no key material in play."""
    proc = subprocess.run(
        [tallow, "llm", "verify", pid],
        capture_output=True,
        text=True,
        timeout=120,
    )
    out = (proc.stdout + proc.stderr).strip()
    body = out.splitlines()[0] if out else ""
    m = VERIFY_RE.match(body)
    status = "ok" if proc.returncode == 0 and (m is None or m.group(1).lower() == "ok") else "failed"
    text = m.group("body") if m else body
    models = MODELS_RE.search(text)
    latency = MS_RE.search(text)
    return (
        status,
        int(models.group("count")) if models else 0,
        (latency.group("ms") + " ms") if latency else "—",
        text[:200],
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tallow", default="target/debug/tallow")
    ap.add_argument("--config", default=str(CONFIG), help="provider config (default: ~/.config/tallow/llm.toml)")
    ap.add_argument("--stdout", action="store_true")
    args = ap.parse_args()

    providers = load_providers(Path(args.config))
    check_key_permissions(providers)
    if not providers:
        return fail(f"no providers configured in {args.config}")

    rows = []
    for pid, cfg in providers.items():
        protocol = cfg.get("protocol", "openai")
        status, models, latency, detail = verify_one(args.tallow, pid)
        rows.append((pid, protocol, models, latency, status, detail))

    today = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d")
    lines = [
        f"# LLM provider verification — {today}",
        "",
        "Generated by `scripts/llm_verify_matrix.py` from the providers configured in",
        "`~/.config/tallow/llm.toml`. No key material is read, printed or stored: the",
        "table records what each endpoint answered.",
        "",
        "| provider | protocol | models | latency | status | detail |",
        "|---|---|---|---|---|---|",
    ]
    for pid, protocol, models, latency, status, detail in rows:
        lines.append(f"| `{pid}` | {protocol} | {models} | {latency} | {status} | {detail} |")

    live = [r for r in rows if r[4] == "ok"]
    lines += [
        "",
        f"**{len(live)} of {len(rows)} configured providers answered.**",
        "",
    ]
    text = "\n".join(lines)

    if args.stdout:
        print(text)
        return 0 if live else 1

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    out = OUT_DIR / f"llm-verify-{today}.md"
    out.write_text(text)
    print(f"llm_verify_matrix: wrote {out} ({len(live)}/{len(rows)} live)")
    return 0 if live else 1


if __name__ == "__main__":
    sys.exit(main())
