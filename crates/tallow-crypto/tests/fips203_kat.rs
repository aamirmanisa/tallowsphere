#[test]
fn mlkem1024_acvp_keygen_seed_kat() {
    let d: [u8; 32] = hexb(KG_D).try_into().expect("d");
    let z: [u8; 32] = hexb(KG_Z).try_into().expect("z");
    let (ek, dk) = ml_kem_1024::KG::keygen_from_seed(d, z);
    assert_eq!(hexb(KG_EK), ek.into_bytes().to_vec(), "encapsulation key KAT mismatch");
    assert_eq!(hexb(KG_DK), dk.into_bytes().to_vec(), "decapsulation key KAT mismatch");
}

#[test]
fn mlkem1024_acvp_encaps_seed_kat() {
    let ek_bytes: [u8; 1568] = hexb(ED_EK).try_into().expect("ek");
    let ek = ml_kem_1024::EncapsKey::try_from_bytes(ek_bytes).expect("ek parses");
    let m: [u8; 32] = hexb(ED_M).try_into().expect("m");
    let (ssk, ct) = ek.encaps_from_seed(&m);
    assert_eq!(hexb(ED_C), ct.into_bytes().to_vec(), "ciphertext KAT mismatch");
    assert_eq!(hexb(ED_K), ssk.into_bytes().to_vec(), "shared secret KAT mismatch");
}

#[test]
fn mlkem1024_acvp_decaps_kat() {
    let dk_bytes: [u8; 3168] = hexb(ED_DK).try_into().expect("dk");
    let dk = ml_kem_1024::DecapsKey::try_from_bytes(dk_bytes).expect("dk parses");
    let ct_bytes: [u8; 1568] = hexb(ED_C).try_into().expect("c");
    let ct = ml_kem_1024::CipherText::try_from_bytes(ct_bytes).expect("c parses");
    let ssk = dk.try_decaps(&ct).expect("decaps");
    assert_eq!(hexb(ED_K), ssk.into_bytes().to_vec(), "decaps shared secret KAT mismatch");
}

#[test]
fn mlkem1024_acvp_decaps_tampered_ct_implicit_reject() {
    let dk_bytes: [u8; 3168] = hexb(ED_DK).try_into().expect("dk");
    let dk = ml_kem_1024::DecapsKey::try_from_bytes(dk_bytes).expect("dk parses");
    let mut bad: [u8; 1568] = hexb(ED_C).try_into().expect("c");
    bad[0] ^= 0x01;
    let ct = ml_kem_1024::CipherText::try_from_bytes(bad).expect("c parses");
    match dk.try_decaps(&ct) {
        // FIPS 203 decapsulation is implicitly rejecting: a tampered ciphertext
        // must never yield the vector's shared secret.
        Ok(ssk) => assert_ne!(
            hexb(ED_K),
            ssk.into_bytes().to_vec(),
            "tampered ciphertext decapsulated to K (implicit rejection broken)"
        ),
        Err(_) => { /* explicit rejection is an acceptable non-match */ }
    }
}
