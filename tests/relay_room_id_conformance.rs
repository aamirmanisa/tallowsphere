//! Relay room-id conformance vectors — the wire contract's derivation surface.
//!
//! Why this test exists: the room-id derivation is what makes two peers land in the same room. It
//! is reached two ways — by the Rust crates (vendored into the product) and by the Tallow-source
//! surface `RelayRoom.room_id(code)`, which is a *binding* over this implementation
//! (`stdlib/relay_room.tl` documents it as "native: derive_room_id hex"). That binding is assumed
//! faithful everywhere and tested nowhere. This file pins the Rust side against committed vectors;
//! `tests/conformance/relay_room_id.tl` drives the Tallow side against the same file, so a binding
//! that resolves a different version than the crate becomes a visible mismatch instead of a silent
//! interop break at join time.
//!
//! The vectors cover all four input shapes, because the *shape* decides the derivation version
//! (`resolve_room_id`) while the Tallow surface documents its derivation as plain "BLAKE3(code)".
//! If those two ever disagree, the disagreement lands here.
//!
//! Regenerate — only when a derivation change is intended, and say so in the commit:
//!   REGENERATE_ROOM_ID_VECTORS=1 cargo test --test relay_room_id_conformance
//! Then confirm the Tallow side still agrees:
//!   scripts/relay_room_id_conformance.sh

use std::fs;
use std::path::Path;

use tallow_protocol::room::code::{
    is_supported_code, is_v3_passcode, resolve_room_id, RoomIdVersion,
};

/// Vector file, relative to the crate root. One line per case:
/// `code <TAB> room-id-hex <TAB> version-tag <TAB> supported`
const VECTORS: &str = "tests/vectors/relay_room_id.v1.txt";

/// Inputs chosen to hit every derivation path.
const CODES: &[&str] = &[
    "ABCD1234",            // v4 passcode: eight ASCII alphanumerics -> Argon2id v4 derivation
    "abc98765",            // v4 shape, lowercase: shape decides the version, not alphabet membership
    "12345678",            // eight digits: the documented v4 compat edge
    "AB12CD",              // v3 shape: exactly six ASCII alphanumerics -> v2 derivation
    "123456",              // six digits: routes to v2 under the same rule
    "amber-canyon-vista",  // legacy phrase -> BLAKE3, unchanged
];

fn hex(bytes: &[u8]) -> String {
    let mut s = String::with_capacity(bytes.len() * 2);
    for b in bytes {
        s.push_str(&format!("{b:02x}"));
    }
    s
}

fn render() -> String {
    let mut out = String::new();
    out.push_str("# relay room-id conformance vectors — generated by tests/relay_room_id_conformance.rs\n");
    out.push_str("# code\troom-id-hex\tversion\tsupported\n");
    for code in CODES {
        let (room_id, version) = resolve_room_id(code);
        let version = match version {
            RoomIdVersion::V3 => "v4-derivation",
            RoomIdVersion::V2 => "v2-derivation",
            RoomIdVersion::V1 => "legacy-blake3",
        };
        out.push_str(&format!(
            "{code}\t{}\t{version}\t{}\n",
            hex(&room_id),
            is_supported_code(code)
        ));
    }
    out
}

#[test]
fn vectors_match_the_derivation() {
    let rendered = render();
    if std::env::var("REGENERATE_ROOM_ID_VECTORS").is_ok() {
        let path = Path::new(VECTORS);
        if let Some(dir) = path.parent() {
            fs::create_dir_all(dir).expect("create vector dir");
        }
        fs::write(path, &rendered).expect("write vector file");
        eprintln!("regenerated {VECTORS}");
        return;
    }
    let committed = fs::read_to_string(VECTORS)
        .unwrap_or_else(|e| panic!("vector file {VECTORS} unreadable ({e}) — regenerate with REGENERATE_ROOM_ID_VECTORS=1"));
    assert_eq!(
        committed, rendered,
        "the room-id derivation changed and the committed vectors were not regenerated"
    );
}

#[test]
fn the_vectors_cover_every_shape() {
    assert!(
        CODES.iter().any(|c| is_supported_code(c)),
        "no v4-shaped code among the vectors"
    );
    assert!(
        CODES.iter().any(|c| is_v3_passcode(c)),
        "no v3-shaped code among the vectors — the v2 derivation path is untested"
    );
    assert!(
        CODES.iter().any(|c| !is_supported_code(c) && !is_v3_passcode(c)),
        "no legacy-shaped code among the vectors — the BLAKE3 path is untested"
    );
}
