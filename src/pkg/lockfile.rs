use anyhow::{Context, Result};
use semver::Version;
use std::collections::{BTreeMap, HashMap};
use std::fs;
use std::path::Path;

use crate::pkg::resolver::PackageRegistry;

/// Current lockfile format version.
pub const LOCKFILE_VERSION: u32 = 1;

/// A single locked package entry.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LockedPackage {
    pub name: String,
    pub version: Version,
    /// BLAKE3 hex hash of the package archive.
    pub content_hash: String,
    /// Names of direct dependencies (sorted alphabetically).
    pub dependencies: Vec<String>,
}

/// Complete lockfile representing a resolved dependency tree.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Lockfile {
    pub lockfile_version: u32,
    /// Packages sorted by name (BTreeMap guarantees ordering).
    pub packages: BTreeMap<String, LockedPackage>,
}

/// Generate a lockfile from resolved dependency versions.
///
/// `resolved` maps package names to their resolved versions.
/// `registry` provides dependency information for each package.
/// `content_hashes` maps package names to their BLAKE3 content hashes.
pub fn generate_lockfile(
    resolved: &HashMap<String, Version>,
    registry: &dyn PackageRegistry,
    content_hashes: &HashMap<String, String>,
) -> Lockfile {
    let mut packages = BTreeMap::new();

    for (name, version) in resolved {
        let deps = registry
            .dependencies(name, version)
            .unwrap_or_default();
        let mut dep_names: Vec<String> = deps.keys().cloned().collect();
        dep_names.sort();

        let hash = content_hashes
            .get(name)
            .cloned()
            .unwrap_or_default();

        packages.insert(
            name.clone(),
            LockedPackage {
                name: name.clone(),
                version: version.clone(),
                content_hash: hash,
                dependencies: dep_names,
            },
        );
    }

    Lockfile {
        lockfile_version: LOCKFILE_VERSION,
        packages,
    }
}

/// Serialize a lockfile to a deterministic string format.
///
/// CRITICAL: Same input MUST produce byte-identical output.
/// Uses `\n` line endings for cross-platform determinism.
pub fn serialize_lockfile(lockfile: &Lockfile) -> String {
    let mut out = String::new();
    out.push_str("# tallow.lock -- DO NOT EDIT\n");
    out.push_str("# Generated by tallow package manager\n");
    out.push_str(&format!("lockfile-version = {}\n", lockfile.lockfile_version));

    for (_name, pkg) in &lockfile.packages {
        out.push('\n');
        out.push_str("[[package]]\n");
        out.push_str(&format!("name = \"{}\"\n", pkg.name));
        out.push_str(&format!("version = \"{}\"\n", pkg.version));
        out.push_str(&format!("integrity = \"blake3:{}\"\n", pkg.content_hash));

        if pkg.dependencies.is_empty() {
            out.push_str("dependencies = []\n");
        } else {
            let deps: Vec<String> = pkg.dependencies.iter().map(|d| format!("\"{}\"", d)).collect();
            out.push_str(&format!("dependencies = [{}]\n", deps.join(", ")));
        }
    }

    out
}

/// Parse a lockfile from its string content.
pub fn parse_lockfile(content: &str) -> Result<Lockfile> {
    let mut lockfile_version: Option<u32> = None;
    let mut packages = BTreeMap::new();

    // State machine for parsing
    let mut current_pkg: Option<PartialPackage> = None;

    for line in content.lines() {
        let trimmed = line.trim();

        // Skip comments and empty lines (unless we're accumulating a package)
        if trimmed.starts_with('#') {
            continue;
        }

        if trimmed.starts_with("lockfile-version") {
            let val = trimmed
                .split('=')
                .nth(1)
                .map(|s| s.trim())
                .context("invalid lockfile-version line")?;
            lockfile_version = Some(
                val.parse::<u32>()
                    .context("lockfile-version must be an integer")?,
            );
            continue;
        }

        if trimmed == "[[package]]" {
            // Flush previous package
            if let Some(pkg) = current_pkg.take() {
                let lp = pkg.finalize()?;
                packages.insert(lp.name.clone(), lp);
            }
            current_pkg = Some(PartialPackage::default());
            continue;
        }

        if trimmed.is_empty() {
            continue;
        }

        // Parse key = value within a package block
        if let Some(ref mut pkg) = current_pkg {
            if let Some((key, val)) = parse_kv(trimmed) {
                match key {
                    "name" => pkg.name = Some(unquote(&val)),
                    "version" => pkg.version = Some(unquote(&val)),
                    "integrity" => {
                        let hash = unquote(&val);
                        pkg.content_hash = Some(
                            hash.strip_prefix("blake3:").unwrap_or(&hash).to_string(),
                        );
                    }
                    "dependencies" => {
                        pkg.dependencies = Some(parse_string_array(&val));
                    }
                    _ => {} // Ignore unknown fields for forward compat
                }
            }
        }
    }

    // Flush last package
    if let Some(pkg) = current_pkg.take() {
        let lp = pkg.finalize()?;
        packages.insert(lp.name.clone(), lp);
    }

    let version = lockfile_version.unwrap_or(1);

    Ok(Lockfile {
        lockfile_version: version,
        packages,
    })
}

/// Write a lockfile to disk.
pub fn write_lockfile(lockfile: &Lockfile, path: &Path) -> Result<()> {
    let content = serialize_lockfile(lockfile);
    // Write with explicit \n line endings (not platform default)
    fs::write(path, content.as_bytes())
        .with_context(|| format!("failed to write lockfile to {}", path.display()))
}

/// Read and parse a lockfile from disk.
pub fn read_lockfile(path: &Path) -> Result<Lockfile> {
    let content = fs::read_to_string(path)
        .with_context(|| format!("failed to read lockfile from {}", path.display()))?;
    parse_lockfile(&content)
}

// --- Internal helpers ---

#[derive(Default)]
struct PartialPackage {
    name: Option<String>,
    version: Option<String>,
    content_hash: Option<String>,
    dependencies: Option<Vec<String>>,
}

impl PartialPackage {
    fn finalize(self) -> Result<LockedPackage> {
        let name = self.name.context("package missing 'name' field")?;
        let version_str = self.version.context("package missing 'version' field")?;
        let version = Version::parse(&version_str)
            .with_context(|| format!("invalid version '{}' for package '{}'", version_str, name))?;

        Ok(LockedPackage {
            name,
            version,
            content_hash: self.content_hash.unwrap_or_default(),
            dependencies: self.dependencies.unwrap_or_default(),
        })
    }
}

fn parse_kv(line: &str) -> Option<(&str, String)> {
    let eq_pos = line.find('=')?;
    let key = line[..eq_pos].trim();
    let val = line[eq_pos + 1..].trim().to_string();
    Some((key, val))
}

fn unquote(s: &str) -> String {
    s.trim_matches('"').to_string()
}

fn parse_string_array(s: &str) -> Vec<String> {
    let inner = s.trim();
    let inner = inner.strip_prefix('[').unwrap_or(inner);
    let inner = inner.strip_suffix(']').unwrap_or(inner);
    let inner = inner.trim();

    if inner.is_empty() {
        return Vec::new();
    }

    inner
        .split(',')
        .map(|item| unquote(item.trim()))
        .filter(|s| !s.is_empty())
        .collect()
}
