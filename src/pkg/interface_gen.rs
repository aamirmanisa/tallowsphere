//! Package interface file (.tli) generation.
//!
//! Generates `.tli` files containing only public API surface:
//! function signatures, struct/enum definitions, type aliases, and constants.
//! No implementation code (function bodies) is included.

use std::fmt::Write;
use std::path::Path;

use crate::ast::*;

/// Generate interface file content from a parsed AST.
///
/// The output is a valid Tallow syntax subset containing:
/// - Function declarations with signatures (no bodies)
/// - Struct declarations with fields
/// - Enum declarations with variants
/// - Type aliases
/// - Const declarations
///
/// Impl block methods are emitted as standalone `fn StructName.method(...)` declarations.
pub fn generate_interface(items: &[Item]) -> String {
    let mut out = String::new();
    writeln!(out, "// Generated by tallow 0.3.0 -- DO NOT EDIT").unwrap();
    writeln!(out).unwrap();

    for item in items {
        match item {
            Item::Fn(f) => {
                emit_fn_signature(&mut out, f, None);
            }
            Item::Struct(s) => {
                emit_struct(&mut out, s);
            }
            Item::Enum(e) => {
                emit_enum(&mut out, e);
            }
            Item::Const(c) => {
                emit_const(&mut out, c);
            }
            Item::TypeAlias(t) => {
                emit_type_alias(&mut out, t);
            }
            Item::Impl(imp) => {
                // Emit methods as StructName.method() signatures
                for method in &imp.methods {
                    emit_fn_signature(&mut out, method, Some(&imp.target));
                }
            }
            Item::Import(_) => {
                // Skip imports -- interface consumers manage their own
            }
            Item::Trait(t) => {
                out.push_str(&format!("trait {} {{\n", t.name));
                for method in &t.methods {
                    out.push_str(&format!("    fn {}(", method.name));
                    for (i, p) in method.params.iter().enumerate() {
                        if i > 0 { out.push_str(", "); }
                        out.push_str(&p.name);
                    }
                    out.push(')');
                    out.push('\n');
                }
                out.push_str("}\n\n");
            }
        }
    }

    out
}

/// Write interface file to disk.
pub fn write_interface(items: &[Item], output_path: &Path) -> std::io::Result<()> {
    let content = generate_interface(items);
    std::fs::write(output_path, content)
}

// ── Internal helpers ────────────────────────────────────────────────────────

fn emit_fn_signature(out: &mut String, f: &FnDecl, impl_target: Option<&str>) {
    // Annotations
    for ann in &f.annotations {
        write!(out, "@{}", ann.name).unwrap();
        if !ann.args.is_empty() {
            write!(out, "(...)").unwrap();
        }
        writeln!(out).unwrap();
    }

    if f.is_async {
        write!(out, "async ").unwrap();
    }

    write!(out, "fn ").unwrap();

    if let Some(target) = impl_target {
        write!(out, "{target}.").unwrap();
    }

    write!(out, "{}", f.name).unwrap();

    // Type params
    if !f.type_params.is_empty() {
        write!(out, "<{}>", f.type_params.join(", ")).unwrap();
    }

    // Params
    write!(out, "(").unwrap();
    for (i, p) in f.params.iter().enumerate() {
        if i > 0 {
            write!(out, ", ").unwrap();
        }
        write!(out, "{}: {}", p.name, format_type(&p.ty)).unwrap();
    }
    write!(out, ")").unwrap();

    // Return type
    if let Some(ref ret) = f.return_type {
        write!(out, " -> {}", format_type(ret)).unwrap();
    }

    writeln!(out, ";").unwrap();
}

fn emit_struct(out: &mut String, s: &StructDecl) {
    write!(out, "struct {}", s.name).unwrap();
    if !s.type_params.is_empty() {
        write!(out, "<{}>", s.type_params.join(", ")).unwrap();
    }
    writeln!(out, " {{").unwrap();

    for field in &s.fields {
        writeln!(out, "    {}: {},", field.name, format_type(&field.ty)).unwrap();
    }

    writeln!(out, "}}").unwrap();
}

fn emit_enum(out: &mut String, e: &EnumDecl) {
    write!(out, "enum {}", e.name).unwrap();
    if !e.type_params.is_empty() {
        write!(out, "<{}>", e.type_params.join(", ")).unwrap();
    }
    writeln!(out, " {{").unwrap();

    for variant in &e.variants {
        if variant.fields.is_empty() {
            writeln!(out, "    {},", variant.name).unwrap();
        } else {
            write!(out, "    {}(", variant.name).unwrap();
            for (i, f) in variant.fields.iter().enumerate() {
                if i > 0 {
                    write!(out, ", ").unwrap();
                }
                write!(out, "{}: {}", f.name, format_type(&f.ty)).unwrap();
            }
            writeln!(out, "),").unwrap();
        }
    }

    writeln!(out, "}}").unwrap();
}

fn emit_const(out: &mut String, c: &ConstDecl) {
    write!(out, "const {}", c.name).unwrap();
    if let Some(ref ty) = c.ty {
        write!(out, ": {}", format_type(ty)).unwrap();
    }

    // Emit value for simple literals
    match &c.value.kind {
        ExprKind::StringLit(s) => write!(out, " = \"{}\"", s).unwrap(),
        ExprKind::IntLit(n) => write!(out, " = {}", n).unwrap(),
        ExprKind::FloatLit(f) => write!(out, " = {}", f).unwrap(),
        ExprKind::BoolLit(b) => write!(out, " = {}", b).unwrap(),
        _ => {} // complex expressions omitted
    }

    writeln!(out).unwrap();
}

fn emit_type_alias(out: &mut String, t: &TypeAlias) {
    write!(out, "type {}", t.name).unwrap();
    if let Some(qualifier) = t.qualifier {
        match qualifier {
            TypeQualifier::Private => write!(out, " = private {}", format_type(&t.ty)).unwrap(),
            TypeQualifier::Secret => write!(out, " = secret {}", format_type(&t.ty)).unwrap(),
        }
    } else {
        write!(out, " = {}", format_type(&t.ty)).unwrap();
    }
    writeln!(out).unwrap();
}

fn format_type(ty: &TypeExpr) -> String {
    match &ty.kind {
        TypeExprKind::Named(name) => name.clone(),
        TypeExprKind::Generic { name, args } => {
            let args_str: Vec<_> = args.iter().map(|a| format_type(a)).collect();
            format!("{}<{}>", name, args_str.join(", "))
        }
        TypeExprKind::Slice(inner) => {
            format!("[]{}", format_type(inner))
        }
        TypeExprKind::Optional(inner) => {
            format!("{}?", format_type(inner))
        }
        TypeExprKind::Tuple(types) => {
            let parts: Vec<_> = types.iter().map(|t| format_type(t)).collect();
            format!("({})", parts.join(", "))
        }
        TypeExprKind::Function { params, return_type } => {
            let params_str: Vec<_> = params.iter().map(|p| format_type(p)).collect();
            format!("fn({}) -> {}", params_str.join(", "), format_type(return_type))
        }
        TypeExprKind::Boxed(inner) => format!("Box<{}>", format_type(inner)),
        TypeExprKind::ImplTrait(name) => format!("impl {name}"),
        TypeExprKind::DynTrait(name) => format!("dyn {name}"),
    }
}

// ── Tests ───────────────────────────────────────────────────────────────────

#[cfg(test)]
mod tests {
    use super::*;
    use crate::lexer;
    use crate::parser::Parser;

    fn parse_items(source: &str) -> Vec<Item> {
        let (tokens, _) = lexer::tokenize(source);
        let program = Parser::parse(tokens).unwrap();
        program.items
    }

    #[test]
    fn test_generate_fn_signature() {
        let items = parse_items("fn add(a: i32, b: i32) -> i32 { a + b }");
        let iface = generate_interface(&items);
        assert!(iface.contains("fn add(a: i32, b: i32) -> i32;"));
        // Body should NOT be present
        assert!(!iface.contains("a + b"));
    }

    #[test]
    fn test_generate_struct() {
        let items = parse_items("struct Config { host: String, port: u16 }");
        let iface = generate_interface(&items);
        assert!(iface.contains("struct Config {"));
        assert!(iface.contains("host: String,"));
        assert!(iface.contains("port: u16,"));
        assert!(iface.contains("}"));
    }

    #[test]
    fn test_generate_enum_variants() {
        let items = parse_items(
            "enum Status { Active, Inactive, Pending(reason: String) }",
        );
        let iface = generate_interface(&items);
        assert!(iface.contains("enum Status {"));
        assert!(iface.contains("Active,"));
        assert!(iface.contains("Inactive,"));
        assert!(iface.contains("Pending(reason: String),"));
    }

    #[test]
    fn test_generate_type_alias() {
        let items = parse_items("type Email = private String");
        let iface = generate_interface(&items);
        assert!(iface.contains("type Email = private String"));
    }

    #[test]
    fn test_generate_const() {
        let items = parse_items(r#"const VERSION = "1.0.0""#);
        let iface = generate_interface(&items);
        assert!(iface.contains("const VERSION"));
        assert!(iface.contains("\"1.0.0\""));
    }

    #[test]
    fn test_body_stripped() {
        let items = parse_items(
            r#"fn complex(x: i32) -> i32 {
    let y = x * 2
    let z = y + 1
    z
}"#,
        );
        let iface = generate_interface(&items);
        assert!(iface.contains("fn complex(x: i32) -> i32;"));
        assert!(!iface.contains("let y"));
        assert!(!iface.contains("let z"));
    }

    #[test]
    fn test_roundtrip_parseable() {
        // Generate interface from source, then verify structs/enums/consts
        // are parseable. Function signatures use `;` terminator which is
        // a .tli convention (not full Tallow syntax), so we replace `;` with
        // `{}` for roundtrip parsing validation.
        let source = r#"
fn add(a: i32, b: i32) -> i32 { a + b }
struct Point { x: f64, y: f64 }
enum Color { Red, Green, Blue }
const MAX: i32 = 100
"#;
        let items = parse_items(source);
        let iface = generate_interface(&items);

        // Replace `fn ...;` with `fn ... {}` for parser compatibility
        let parseable = iface
            .lines()
            .map(|line| {
                if line.starts_with("fn ") && line.ends_with(';') {
                    format!("{} {{}}", &line[..line.len() - 1])
                } else if line.starts_with("async fn ") && line.ends_with(';') {
                    format!("{} {{}}", &line[..line.len() - 1])
                } else {
                    line.to_string()
                }
            })
            .collect::<Vec<_>>()
            .join("\n");

        let (tokens, _) = lexer::tokenize(&parseable);
        let result = Parser::parse(tokens);
        assert!(
            result.is_ok(),
            "generated .tli (with body stubs) should be parseable: {:?}",
            result.err()
        );
    }

    #[test]
    fn test_async_fn_signature() {
        let items = parse_items("async fn fetch_data(url: String) -> String { url }");
        let iface = generate_interface(&items);
        assert!(iface.contains("async fn fetch_data(url: String) -> String;"));
    }

    #[test]
    fn test_generic_fn_signature() {
        let items = parse_items("fn first<T>(items: []T) -> T { items }");
        let iface = generate_interface(&items);
        assert!(iface.contains("fn first<T>(items: []T) -> T;"));
    }

    #[test]
    fn test_header_present() {
        let items = parse_items("fn noop() {}");
        let iface = generate_interface(&items);
        assert!(iface.starts_with("// Generated by tallow 0.3.0 -- DO NOT EDIT"));
    }
}
